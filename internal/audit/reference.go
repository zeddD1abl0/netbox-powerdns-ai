package audit

import (
	"fmt"
	"io"
	"strings"
)

// WriteReference writes the audit events' reference page, in Markdown, from
// the actions' declarations.
func WriteReference(w io.Writer) error {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("---\ntitle: Audit events\nweight: 42\n---\n\n")
	p("<!-- Generated by internal/cmd/gendocs from the action declarations in internal/audit.\n")
	p("     Don't edit this page: change the declarations, then run `make generate`. -->\n\n")
	p("# Audit events\n\n")
	p("nbpdns records every change of its state as an event in its audit trail,\n")
	p("in its database, in the same transaction as the change (ADR-0039). Each\n")
	p("event holds the SHA-384 of its contents and of the event before it, so\n")
	p("that `nbpdns audit verify` finds an event that was changed, removed or\n")
	p("inserted. `nbpdns audit list` reads the trail.\n\n")
	p("## Fields\n\n")
	p("| Field | Holds |\n|---|---|\n")
	for _, f := range [][2]string{
		{"`seq`", "The event's place in the trail, from 1."},
		{"`time`", "When it was recorded, in UTC, to the microsecond, such as `2026-10-10T01:02:03.000004Z`."},
		{"`actor`", "Who made the change: `os-user:<name>`, a person at the command line, by their operating system account; `system`, nbpdns itself; or `file:<path>`, the config file."},
		{"`action`", "What the change was: one of the actions below."},
		{"`target`", "What it was made to, as `<type>:<id>`."},
		{"`before`, `after`", "The target's values, as JSON, before and after the change, if it had any. Secrets are never among them."},
		{"`reason`", "Why, as the person who made the change gave it, with `--reason`."},
		{"`outcome`", "`success` or `failure`."},
		{"`trace_id`, `request_id`", "Those of the command or request that made the change, as its log lines carry them."},
		{"`source_ip`", "The address that the change came from, if it came over the network."},
		{"`prev_hash`", "The `hash` of the event before it, or empty for the trail's first event."},
		{"`hash`", "The hex SHA-384 of the event's other fields: a JSON object, without spaces, of the other fields, in this table's order, " +
			"with `before` and `after` as strings that hold their JSON, or `null`."},
	} {
		p("| %s | %s |\n", f[0], f[1])
	}
	p("\n## Actions\n\n")
	p("| Action | Target type | Actor | Recorded when |\n|---|---|---|---|\n")
	for _, d := range defs {
		p("| [`%s`](#%s) | `%s` | %s | %s |\n", d.Action, anchor(d.Action), d.Target, d.Actor, d.Summary)
	}
	for _, d := range defs {
		p("\n### `%s`\n\n%s\n\n", d.Action, d.Summary)
		p("- **Target:** type `%s`, named by %s\n", d.Target, d.TargetID)
		p("- **Actor:** %s\n", d.Actor)
		p("- **Before:** %s\n", orNothing(d.Before))
		p("- **After:** %s\n", orNothing(d.After))
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// anchor returns the heading anchor of an action's section.
func anchor(a Action) string { return strings.ReplaceAll(string(a), ".", "") }

func orNothing(s string) string {
	if s == "" {
		return "nothing."
	}
	return s
}
